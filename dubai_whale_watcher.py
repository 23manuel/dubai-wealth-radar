# LAYER 1 & 2: THE MATRIX (Simulator - Persistent Property Fix)
# ---------------------------------------------------------
class DubaiWealthSimulator:
    def __init__(self, num_users=9900, days=365):
        self.num_users = num_users
        self.days = days
        self.start_date = datetime(2025, 3, 22)
        self.states = ['normal', 'emerging', 'active_whale', 'anchored_whale', 'exit_risk']
        self.transitions = {
            'normal': {'normal': 0.94, 'emerging': 0.05, 'exit_risk': 0.01},
            'emerging': {'emerging': 0.80, 'active_whale': 0.15, 'normal': 0.05},
            'active_whale': {'active_whale': 0.70, 'anchored_whale': 0.25, 'exit_risk': 0.05},
            'anchored_whale': {'anchored_whale': 0.95, 'exit_risk': 0.05},
            'exit_risk': {'exit_risk': 0.90, 'normal': 0.10}
        }

    def generate_data(self):
        data, user_metadata = [], []
        for user_id in range(self.num_users):
            current_state = np.random.choice(self.states, p=[0.7, 0.2, 0.05, 0.03, 0.02])
            whale_start_t = None

            for day in range(self.days):
                date = self.start_date + timedelta(days=day)

                prev_state = current_state
                current_state = np.random.choice(list(self.transitions[prev_state].keys()), p=list(self.transitions[prev_state].values()))

                if current_state in ['active_whale', 'anchored_whale'] and whale_start_t is None:
                    whale_start_t = date

                if np.random.rand() < 0.25: # Slightly reduced noise
                    data.append(self._create_event(user_id, date, 'lifestyle_noise', np.random.uniform(50, 300)))

                if current_state == 'emerging' and np.random.rand() < 0.10:
                    for _ in range(np.random.randint(1, 4)):
                        data.append(self._create_event(user_id, date, 'crypto_offramp', np.random.uniform(20000, 80000)))

                elif current_state in ['active_whale', 'anchored_whale']:
                    # CHATGPT FIX: Persistent, structured property behavior
                    if np.random.rand() < 0.02:
                        data.append(self._create_event(user_id, date, 'property_acq', 250000))
                    if np.random.rand() < 0.04:
                        data.append(self._create_event(user_id, date, 'property_commitment', 50000))

                    if current_state == 'active_whale' and np.random.rand() < 0.05:
                        data.append(self._create_event(user_id, date, 'luxury_retail', np.random.uniform(10000, 50000)))

                if current_state == 'anchored_whale':
                    if date.day == 1:
                        data.append(self._create_event(user_id, date, 'residency_anchor', 45000))

                elif current_state == 'exit_risk':
                    exit_intensity = min(0.02 + (day / self.days) * 0.15, 0.20)
                    if np.random.rand() < exit_intensity:
                        data.append(self._create_event(user_id, date, 'wealth_flight', np.random.uniform(50000, 150000)))

            user_metadata.append({
                'user_id': user_id,
                'whale_since': whale_start_t,
                'is_high_value': current_state in ['active_whale', 'anchored_whale']
            })

        return pd.DataFrame(data), pd.DataFrame(user_metadata)

    def _create_event(self, user_id, date, event_type, amount):
        return {'user_id': user_id, 'timestamp': date, 'event_type': event_type, 'amount': round(amount, 2)}

