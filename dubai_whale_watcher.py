# LAYER 3 & 4: THE VECTOR RADAR (Clean Delta Fix)
# ---------------------------------------------------------
DECAY = {"crypto": 0.05, "property": 0.005, "lifestyle": 0.08, "anchor": 0.003, "exit": 0.07}
BUCKET_MAP = {
    "crypto_offramp": "crypto", "property_acq": "property", "property_commitment": "property",
    "luxury_retail": "lifestyle", "lifestyle_noise": "lifestyle",
    "residency_anchor": "anchor", "wealth_flight": "exit"
}

def compute_vector_score(df):
    df = df.sort_values(["user_id", "timestamp"])
    history = []

    for user_id, group in df.groupby("user_id"):
        signals = {"crypto": 0, "property": 0, "lifestyle": 0, "anchor": 0, "exit": 0}
        last_date = None # CHATGPT FIX: Cleaner initialization

        for _, row in group.iterrows():
            current_date = row["timestamp"]
            delta_days = (current_date - last_date).days if last_date else 0

            if delta_days > 0:
                for key in signals:
                    signals[key] *= np.exp(-DECAY[key] * delta_days)

            bucket = BUCKET_MAP.get(row["event_type"])
            if bucket:
                signals[bucket] += np.log1p(row["amount"])

            # Note: total_score removed from tracking to prevent leakage
            history.append({
                "user_id": user_id, "timestamp": current_date,
                "crypto_sig": signals["crypto"], "property_sig": signals["property"],
                "anchor_sig": signals["anchor"], "exit_sig": signals["exit"],
                "lifestyle_sig": signals["lifestyle"]
            })
            last_date = current_date

    return pd.DataFrame(history)

